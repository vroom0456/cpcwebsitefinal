const PHOTO_FETCH_LIMIT = 50000;
const UUID_REGEX = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

const SLUG_TO_EVENT_ID: Record<string, string> = {
  "annual-exhibition-2026": "11111111-1111-1111-1111-111111111104",
  "chaitanya-smriti-2026": "11111111-1111-1111-1111-111111111101",
  "studio-lighting-workshop": "11111111-1111-1111-1111-111111111105",
  "freshers-orientation-2025-26": "11111111-1111-1111-1111-111111111102",
  "monsoon-photowalk-2025": "11111111-1111-1111-1111-111111111103",
  "sudhee-shruthi-2025": "11111111-1111-1111-1111-111111111106",
  "heritage-walk-charminar-2025": "11111111-1111-1111-1111-111111111107",
  "portfolio": "11111111-1111-1111-1111-111111111100",
};

function getFallbackPhotos(eventId: string): Photo[] {
  const targetId = SLUG_TO_EVENT_ID[eventId] || eventId;
  const match = DEFAULT_PHOTOS.filter(
    (p) =>
      p.event_id === targetId ||
      p.event_id === eventId ||
      ((targetId.includes("portfolio") || eventId.includes("portfolio")) &&
        p.event_id === "11111111-1111-1111-1111-111111111100")
  );
  return match;
}

export async function getPhotosForEvent(eventId: string): Promise<Photo[]> {
  try {
    const supabase = createPublicClient();
    let actualId = eventId;

    if (!UUID_REGEX.test(eventId)) {
      const { data: ev } = await supabase
        .from("events")
        .select("id")
        .or(`id.eq.${eventId},slug.eq.${eventId}`)
        .maybeSingle();
      if (ev?.id) actualId = ev.id;
    }

    const { data, error } = await supabase
      .from("photos")
      .select("id, event_id, drive_file_id, filename, subfolder, thumbnail_url, full_url, width, height, is_cover, is_published, created_at, camera_make, camera_model, lens, exif")
      .eq("event_id", actualId)
      .or("is_published.eq.true,is_published.is.null")
      .order("created_at", { ascending: true })
      .range(0, 1500);

    if (error || !data || data.length === 0) {
      // Trigger background sync without blocking the client response
      (async () => {
        try {
          const { data: ev } = await supabase
            .from("events")
            .select("id, drive_folder_id")
            .eq("id", actualId)
            .maybeSingle();

          if (ev?.drive_folder_id) {
            const { syncEventPhotos } = await import("@/lib/drive/drive.service");
            await syncEventPhotos(actualId);
          }
        } catch {
          // Ignore
        }
      })().catch(() => {});

      return getFallbackPhotos(actualId);
    }
    return data as Photo[];
  } catch (err) {
    return getFallbackPhotos(eventId);
  }
}

